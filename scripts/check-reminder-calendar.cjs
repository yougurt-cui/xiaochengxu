const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict');
let store = {};
const ctx = { loadStore: () => store, saveStore: (patch) => Object.assign(store, patch) };
vm.createContext(ctx);
for (const file of ['utils/reminders.js', 'utils/reminder-calendar.js']) vm.runInContext(fs.readFileSync(file, 'utf8').replace(/^import .*;$/gm, '').replace(/export /g, ''), ctx);
vm.runInContext('this.api = { birthdayCountdown, syncBirthdayReminder, listReminders, completeReminder, calendarDays, remindersOnDate, weekStart, shiftDate, localDate }', ctx);
const r = ctx.api, now = new Date(2026, 0, 1, 8).getTime();
const pet = { id: 'p1', name: '豆豆', birthday: '2024-02-29' };
r.syncBirthdayReminder(pet, now);
let birthday = r.listReminders()[0];
assert.equal(r.localDate(birthday.dueAt), '2026-02-28');
r.syncBirthdayReminder(pet, now);
assert.equal(r.listReminders().length, 1);
assert.equal(r.remindersOnDate(r.listReminders(), '2028-02-29').length, 1);
assert.equal(r.remindersOnDate(r.listReminders(), '2028-02-28').length, 0);
r.completeReminder(birthday.id, birthday.dueAt, birthday.dueAt + 1);
const next = r.listReminders()[0].dueAt;
r.syncBirthdayReminder({ ...pet, name: '新名字' }, now);
assert.equal(r.listReminders()[0].dueAt, next);
assert.equal(r.listReminders()[0].title, '新名字的生日');
r.syncBirthdayReminder({ ...pet, birthday: '2024-05-02' }, now);
assert.equal(r.listReminders().length, 1);
assert.equal(r.localDate(r.listReminders()[0].dueAt), '2026-05-02');
r.syncBirthdayReminder({ ...pet, birthday: '' }, now);
assert.equal(r.listReminders().length, 0);
assert.equal(r.weekStart('2026-01-01'), '2025-12-29');
assert.equal(r.shiftDate('2026-01-31', 1), '2026-02-01');
assert.equal(r.calendarDays('2025-12-29', 14, '2026-01-01', []).length, 14);
assert.equal(r.calendarDays('2025-12-29', 14, '2026-01-01', []).filter((d) => d.selected).length, 1);
const oneOff = { id: 'once', dueAt: new Date(2026, 0, 1, 9).getTime(), repeat: 'none' };
assert.equal(r.remindersOnDate([oneOff], '2026-01-02').length, 0);
console.log('PASS: birthday deduplication, update, removal, completion preservation, leap-year recurrence, two-week calendar and year/month boundaries');

assert.equal(r.birthdayCountdown('2020-10-20', new Date(2026, 9, 10, 23)), '距离生日还有10天');
assert.equal(r.birthdayCountdown('2020-10-10', new Date(2026, 9, 10)), '');
assert.equal(r.birthdayCountdown('2020-10-09', new Date(2026, 9, 10)), '');
assert.equal(r.birthdayCountdown('', new Date(2026, 9, 10)), '');
assert.equal(r.birthdayCountdown('2020-02-30', new Date(2026, 0, 1)), '');
assert.equal(r.birthdayCountdown('2024-02-29', new Date(2026, 1, 27)), '距离生日还有1天');
console.log('PASS: birthday countdown, same/past birthday, invalid dates and leap day');
